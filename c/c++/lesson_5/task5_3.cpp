/*Пусть у нас есть кирпич с размерами сторон a, b, c, и есть прямоугольное отвер-
стие размером x на y. Нужно проверить, пройдет ли кирпич в отверстие.
Очевидно, что кирпич пройдет в отверстие, если хотя бы две из его сторон меньше
размеров отверстия. Упорядочим размеры отверстия (x < y) и «выстроим» размеры
сторон кирпича в возрастающем порядке: a < b < c. Тогда для ответа на вопрос
достаточно одной проверки:*/

#include <iostream> 

using namespace std;

int main(){
    double a, b, c;
    cout << "Задайте размер кирпича "; cin >> a >> b >> c;
    double x,y;
    cout << "Задайте размер отверстия "; cin >> x >> y;
    if (x > y) { double t = x; x = y; y = t; }
    if (a > b) { double t = a; a = b; b = t; }
    if (b > c) { double t = b; b = c; c = t; }
    if (a > b) { double t = a; a = b; b = t; }
    if ((a < x)&&(b < y)) cout << "Кирпич пройдет в отверстие!\n";
    else
    cout << "Кирпич не пройдет в отверстие!\n";

}