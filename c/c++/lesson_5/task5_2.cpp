/*Как известно, високосными годами являются все года, которые делятся на 4 без
остатка (остаток равен нулю), за исключением тех, которые делятся на 100. Если
год делится на 100, то он является високосным только в том случае, если делится на
400. Слово «делится» здесь означает, что остаток от деления равен нулю. Напри-
мер, високосными годами являются 1600, 2000, 2004, 1996. А 1900 или 2003 годы
високосными не являются.
Таким образом в условном операторе надо проверять, равны ли остатки от деления
на 4, 100, 400 нулю или не равны. Очевидно, что переменная, в которой должен
храниться год, должна быть целая беззнаковая.*/

#include <iostream>

using namespace std;


int main(){
    unsigned int year {0};
    // unsingned (от английского без знака) - Это модификатор который  говрит,
    // что переменная может хранить только не отрицательные числа
    cout << "Задайте год: "; cin >> year;

    if ((year % 100) != 0 )
        if ((year %4) == 0 ) cout << "Год высокосный\n";
        else cout << "Год не высокосный\n";
    else
        if ((year % 400) == 0) cout << "Год высокосный\n";
        else cout << "Год не высокосный \n";
    return 0;

}