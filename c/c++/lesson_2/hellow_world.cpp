#include <iostream>     // Англиское слово include буквально переводится как содержать в себе
                        // (< и >) Эти скобки признак стандартного заголовка, 
                        // а имя iostream в данном случае часть стандартной библиотеки 
                        // в данном случаии средства потокового ввода/вывода


using namespace std;    // тоже имеет отношение к стандартной библиотеке 
                        // все именаобъявлены  в стандартной библиотеке входят в стандартное пространство std::.
                        // если убрать эту строчку то програмы выдаст ошибку и тогда программу нужно будет переписать т.к 
                        // cout endl тоже придется писать с std::.
                        // пример -> std :: cout <<"Hello World!" << std:: endl;

int main()              // функция main в каждой программе должна быть функция main, она является гланой название функций может быть и другое
                        // - Сначало указывается тип возращаемого значения int (integer) - целое
                        // - main - обезательное имя главной функции и другое имя нельзя писать
                        // - пустые скобки () посли функции main  показывают, что параметры функции отсуствуют

                        // Далее идет тело функии 
                        // конструкция с фигурнами {} блоками называется блоками
                        // операторы, записанные в теле, выполняюся последовательно заверашаобтся символом;
{
    cout <<"Hello World!" << endl;  // в нашей программе в теле функциии написанны всего два оператора 
                                    // cout << "Hello World!" << edl; (оперотор вывода)
                                    // return 0; (оперотор возращение )
    return 0;
}
