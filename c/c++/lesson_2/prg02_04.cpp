/*
Решим задачу;
У одного ученика было 8 конфет, у другого ученика было 6 конфет. 
Первый ученик отдал второму 1 конфету. Сколько конфет стало у учеников?
*/

#include <iostream>

using namespace std;
int main(){
    cout 
        << "У 1-го ученика стало 8-1 = " << (8-1) << " конфет\n"
        << "У 2-го ученика стало 6+1 = " << (6+1) << " конфет\n";
    return 0;
}