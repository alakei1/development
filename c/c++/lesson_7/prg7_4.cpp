double Square(double a,double b){
    return a*b;
}
double Perimeter(double a, double b){
    return 2*(a+b);
}
//Обычно говорят, что в C/C++ существует три способа передачи параметров:
/*
    Пердача по значению - самый распрастраненый и надежный метод передачи,
    работающий и во могих других языках прогромирования. 
    При этом способе передачи параметров предпологается, что каждыйобъявленный в загоовке параметр
    является локальной переменной в теле функции. 
    Поэтому любые его изменеия происходят только в внутрифункции и не влияют на парамеры в не её.
    Передача параметров по значению эквивалента выполнению операции присваивания 
    имя_переменной = выражение
    В частности, есл выражение - константа переменная, совподают по типу с параметром, 
    то выражение просто копируется в параметр.Копирование значения фактического параметра в 
    локальную переменную требует времени, поэтому способ передачи параметров по значению обычно применяется для данных
    встроенных типов, время копирование которых мало.
*/
