/*Написать программу, которая определяет, делится ли сумма цифр заданного
числа N на k без остатка; 2 ≤ N ≤ 1000000000, 2 ≤ k ≤ 100.*/

#include <iostream>

using namespace std;

int main() {
    long long n {};
    int k {};
    int sum_n {};

    cout << "Введите число N (2 <= N <= 1 000 000 000) -> ";
    cin >> n;
    cout << "Введите делитель k (2 <= k <= 100) -> ";
    cin >> k;

    if ((n < 2) || (n > 1000000000) || (k < 2) || (k > 100)) {
        cout << "Одно из чисел не соответствует диапазону!" << endl;
    } else {
        long long temp = n; 
        while (temp > 0) {
            sum_n += temp % 10; 
            temp /= 10;         
        }

        cout << ((sum_n % k == 0)
            ? "Сумма цифр числа N делится на число k без остатка"
            : "Сумма цифр числа N не делится на число k без остатка") << endl;
    }

    return 0;
}
