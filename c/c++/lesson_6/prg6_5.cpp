// Оператор for со счетчиком
/*Расматривая оба варианта программмы про таблцу умнажуние, можно заметить,
что организаия цикла в обеих программах имеет некоторые сходные черты :
1. в том и другом варианте у нас есть выражени переменная-счетчик, которой один раз 
присвается начально значение.
2. эта переменная увеличивается при каждой, интеграциии ишаг увелиния равен 1
3. на каждом шаге цикла выполняется проверка условияэ
Практика показала, что такие циклы встречаются в программах оень часто. 
Поэтом разработчики С включили третий вид оператора икла, который и так называется икл со счетчиком:
for (выражение_1; учловие; выражение_3) оператор*/

# include<iostream> 

using namespace std;

int main () {
    int num;
    cout << "Ведите множитель от 0 до 9: "; cin >> num;
    if ((0<num)&&(num<10))
        {
            for(int i; i<10; ++i)
                cout << num << '*' << i << '=' << num*i << endl;
        }
    else cout << "множитель не в диапазоне (0:9) ведите верное значение" << endl;
}