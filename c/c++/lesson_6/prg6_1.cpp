/*Знакомство с циклами (goto)*/
#include <iostream>

using namespace std;

int main (){
    /*Идефикатор start (начало), после которого поставленно двоеточие,называется меткой.
    В качестве метки можно указывать любой допустимый индефикатор. Этот идефикатор предварительно никак не объявляется.
    Двоеточие после него и указывает, что этот индефикатор является меткой. В блоке условног оператора записан оператор goto
    (иди к ), в котором эта метка и задана. Оператор goto ак и называется: Оператор перехода. и его действие заключается именно в том,
    что программа возращается к матка start и работа начинается занаво*/

    cout << "Определение высокосности года\n";
    cout << "Для завершение работы ведите 0.\n";

    unsigned int year {};

    start: //Метка

    cout << "Задайте год: "; cin >> year;

    if (year>0){

        if (((year % 100 ) && (!(year % 4))) || (!(year % 400)))
        cout << "Год высокосный!\n";

        else cout << "Год не високосный!\n";

        goto start; // Переход на метку
    }

    cout << "Заканчиваем программму\n";
    return 0;
}