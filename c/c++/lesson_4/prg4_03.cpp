#include <iostream>
// деление по модолю 
using namespace std;

int main(){
    /*
    Знак зависит не от делителя, а от делимого деление 
    по модолю имеют свои собственые название
    div
    mod
    */
    cout << 5   % 2 << endl;
    cout <<-5   % 2 << endl;
    cout << 5   %-2 << endl;
    cout <<-5   %-2 << endl;

return 0;
}