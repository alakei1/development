#include <iostream>

using namespace std;

int main(){
    cout << "Задайте стороны прямоугольника\n";
    
    double a; cout << "A = "; cin >> a;
    double b; cout << "B = "; cin >> b;
    double S = a*b;
    double P = 2*(a+b);

    cout 
        <<"Площадь прямоугольник = " << S << endl
        <<"Периметр Прямоугольника  = " << P << endl;

    return 0;
}