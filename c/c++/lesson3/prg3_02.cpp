#include <iostream>
#include <string>

using namespace std;

int main(){
    cout << "Как вас зовут?" << endl;
    string name;  // Перменные для хранение имени
    string surname; // Переменная для хранения фамилии

    cin >> name >> surname;

    const string greeting = "|Привет, "+ name +" "+ surname +"!|"; // Объявлена пременная greeting в ней выполняется операция коккотенации
    // так же написан оператор const  он дает полный запрет на изменение переменной и требует явной инициализациии переменной
    // Инициализирующее значение присваивается переменной при объявлении, и в дальнейшем это значение в переменной нельзя менять
    // поэтому такие переменные называются поименноваными константами
    const string asterisks(greeting.length(),'*'); // вырожение инициализируется не знаком присваиванияв круглых скобках 
    // первое вырожение greeting.length() -> Означает вичислить длину строки  в данной переменной
    //второе выроение это символьный итерал из которого должна формироватся строка рамки.Можно использовать другой символ
    
    cout<< asterisks << '\n'
        << greeting << '\n'
        << asterisks << '\n';
    
        return 0 ;

}

